/* Standard MSX floppy geometries; matches blueMSX Bios/Patch.c formatInfo
** rows for backward compatibility with the disk driver's expectations. */
typedef struct {
    int             sizeKB;
    unsigned short  totalSectors;
    unsigned char   sides;
    unsigned char   sectorsPerTrack;
    unsigned char   sectorsPerFat;
    unsigned short  dirEntries;
    unsigned char   sectorsPerCluster;
    unsigned char   mediaByte;
} FloppyGeom;

static const FloppyGeom kFloppyGeoms[] = {
    /* KB    sects  sides spt spf dir spc  media */
    {  720,  1440,  2,    9,  3,  112, 2,  0xF9 },
    {  640,  1280,  2,    8,  2,  112, 2,  0xFB },
    {  360,   720,  1,    9,  2,  112, 2,  0xF8 },
    {  320,   640,  1,    8,  1,  112, 2,  0xFA }
};

static const FloppyGeom* findGeom(int sizeBytes)
{
    unsigned i;
    for (i = 0; i < sizeof(kFloppyGeoms)/sizeof(kFloppyGeoms[0]); i++) {
        if (kFloppyGeoms[i].sizeKB * 1024 == sizeBytes) return &kFloppyGeoms[i];
    }
    return NULL;
}

static void put16le(unsigned char* p, unsigned short v)
{
    p[0] = (unsigned char)(v & 0xFF);
    p[1] = (unsigned char)((v >> 8) & 0xFF);
}

/* Patch the standard FAT12 BPB fields (offsets 11-27) in a boot sector copy. */
static void patchBpb(unsigned char* sec, const FloppyGeom* g)
{
    put16le(sec + 11, SECTOR_SIZE);
    sec[13] = g->sectorsPerCluster;
    put16le(sec + 14, 1);
    sec[16] = 2;
    put16le(sec + 17, g->dirEntries);
    put16le(sec + 19, g->totalSectors);
    sec[21] = g->mediaByte;
    put16le(sec + 22, g->sectorsPerFat);
    put16le(sec + 24, g->sectorsPerTrack);
    put16le(sec + 26, g->sides);
}

static const unsigned char* pickTemplate(DiskFormatType fmt)
{
    switch (fmt) {
    case DiskFormatMsxDos1: return kDos1BootBlock;
    case DiskFormatMsxDos2: return kDos2BootBlock;
    case DiskFormatNextor:  return kNextorFat12BootBlock;
    default:                return NULL;
    }
}

static int writeFill(FILE* f, unsigned char byte, long sizeBytes)
{
    unsigned char buf[SECTOR_SIZE];
    long remain = sizeBytes;
    memset(buf, byte, SECTOR_SIZE);
    while (remain > 0) {
        long chunk = remain > SECTOR_SIZE ? SECTOR_SIZE : remain;
        if (fwrite(buf, 1, (size_t)chunk, f) != (size_t)chunk) return 0;
        remain -= chunk;
    }
    return 1;
}

/* Silence unused-symbol warning for the FAT16 template (kept for later). */
static const void* diskFormatUnusedSymbols[] = { kNextorFat16BootBlock };

int diskFormatWriteBootSector(unsigned char* dst, int sizeBytes,
                              DiskFormatType fmt)
{
    const FloppyGeom* g;
    const unsigned char* tmpl;
    if (dst == NULL) return 0;
    g = findGeom(sizeBytes);
    tmpl = pickTemplate(fmt);
    if (g == NULL || tmpl == NULL) return 0;
    memcpy(dst, tmpl, SECTOR_SIZE);
    patchBpb(dst, g);
    return 1;
}

int diskImageCreate(const char* path, int sizeBytes, DiskFormatType fmt)
{
    FILE* f;
    const FloppyGeom* g;
    const unsigned char* tmpl;
    unsigned char sector[SECTOR_SIZE];
    int fatIdx, i;
    long dataStartSec, dataEndSec, fillBytes;
    (void)diskFormatUnusedSymbols;

    if (path == NULL || sizeBytes <= 0) return 0;

    if (fmt == DiskFormatUnformatted) {
        int svi = (sizeBytes == 338 * 1024 || sizeBytes == 168 * 1024);
        f = fopen(path, "wb");
        if (f == NULL) return 0;
        if (!writeFill(f, (unsigned char)(svi ? 0xE5 : 0x00), sizeBytes)) {
            fclose(f);
            return 0;
        }
        fclose(f);
        return 1;
    }

    g = findGeom(sizeBytes);
    tmpl = pickTemplate(fmt);
    if (g == NULL || tmpl == NULL) {
        /* Unsupported size/format combo: fall back to zero-fill so the file */
        /* still exists.  Caller UI should disable such combos where useful. */
        f = fopen(path, "wb");
        if (f == NULL) return 0;
        if (!writeFill(f, 0x00, sizeBytes)) { fclose(f); return 0; }
        fclose(f);
        return 1;
    }

    f = fopen(path, "wb");
    if (f == NULL) return 0;

    memcpy(sector, tmpl, SECTOR_SIZE);
    patchBpb(sector, g);
    if (fwrite(sector, 1, SECTOR_SIZE, f) != SECTOR_SIZE) goto fail;

    for (fatIdx = 0; fatIdx < 2; fatIdx++) {
        memset(sector, 0, SECTOR_SIZE);
        sector[0] = g->mediaByte;
        sector[1] = 0xFF;
        sector[2] = 0xFF;
        if (fwrite(sector, 1, SECTOR_SIZE, f) != SECTOR_SIZE) goto fail;
        memset(sector, 0, SECTOR_SIZE);
        for (i = 1; i < g->sectorsPerFat; i++) {
            if (fwrite(sector, 1, SECTOR_SIZE, f) != SECTOR_SIZE) goto fail;
        }
    }

    memset(sector, 0, SECTOR_SIZE);
    for (i = 0; i < g->dirEntries / 16; i++) {
        if (fwrite(sector, 1, SECTOR_SIZE, f) != SECTOR_SIZE) goto fail;
    }

    dataStartSec = 1 + 2 * g->sectorsPerFat + g->dirEntries / 16;
    dataEndSec   = g->totalSectors;
    fillBytes    = (dataEndSec - dataStartSec) * SECTOR_SIZE;
    if (!writeFill(f, 0xE5, fillBytes)) goto fail;

    fclose(f);
    return 1;

fail:
    fclose(f);
    return 0;
}
